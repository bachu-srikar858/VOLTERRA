/**
 * Generates supabase/seed.sql from src/lib/demo/seed.ts so the Supabase
 * backend starts with the same catalog as demo mode.
 *
 * Usage:  node scripts/generate-supabase-seed.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const seedSrc = readFileSync(join(root, 'src/lib/demo/seed.ts'), 'utf8')
const js = ts.transpileModule(seedSrc, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
}).outputText

const module = { exports: {} }
const fn = new Function('module', 'exports', 'require', js)
fn(module, module.exports, (id) => {
  // seed.ts only uses `import type`, so no runtime imports are expected
  throw new Error(`Unexpected runtime import: ${id}`)
})
const { categories, collections, products } = module.exports

const q = (v) => `'${String(v).replace(/'/g, "''")}'`
const qArr = (arr) => `array[${(arr || []).map(q).join(', ')}]::text[]`
const qJson = (v) => `'${JSON.stringify(v ?? []).replace(/'/g, "''")}'::jsonb`
const d = (v) => (v == null ? 'null' : q(v))

const lines = []
lines.push('-- VOLTERRA seed data — generated by scripts/generate-supabase-seed.mjs')
lines.push('-- Run after supabase/schema.sql in the Supabase SQL editor.')
lines.push('')
lines.push('insert into public.categories (id, name, slug, description, image, sort_order) values')
lines.push(
  categories
    .map((c) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.slug)}, ${d(c.description)}, ${d(c.image)}, ${c.sortOrder})`)
    .join(',\n') + '\non conflict (id) do nothing;',
)
lines.push('')
lines.push('insert into public.collections (id, name, slug, tagline, description, image, dark, category_slugs, product_slugs) values')
lines.push(
  collections
    .map((c) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.slug)}, ${d(c.tagline)}, ${d(c.description)}, ${d(c.image)}, ${c.dark}, ${qArr(c.categorySlugs)}, ${qArr(c.productSlugs)})`)
    .join(',\n') + '\non conflict (id) do nothing;',
)
lines.push('')
lines.push('insert into public.products (id, slug, name, category_id, category_name, gender, price, compare_at_price, rating, review_count, description, images, colors, sizes, sku, technology, materials, fit, care, featured, trending, is_new, collection_ids, tags) values')
lines.push(
  products
    .map(
      (p) => `  (${q(p.id)}, ${q(p.slug)}, ${q(p.name)}, ${d(p.categoryId)}, ${q(p.categoryName)}, ${q(p.gender)}, ${p.price}, ${d(p.compareAtPrice)}, ${p.rating}, ${p.reviewCount}, ${d(p.description)}, ${qArr(p.images)}, ${qJson(p.colors)}, ${qJson(p.sizes)}, ${d(p.sku)}, ${qArr(p.technology)}, ${d(p.materials)}, ${d(p.fit)}, ${qArr(p.care)}, ${p.featured}, ${p.trending}, ${p.isNew}, ${qArr(p.collectionIds)}, ${qArr(p.tags)})`,
    )
    .join(',\n') + '\non conflict (id) do nothing;',
)
lines.push('')
lines.push('-- Make the first sign-up an admin (change the email to yours, then re-run):')
lines.push(`update public.profiles set is_admin = true where email = 'you@example.com';`)

mkdirSync(join(root, 'supabase'), { recursive: true })
const out = join(root, 'supabase/seed.sql')
writeFileSync(out, lines.join('\n'))
console.log(`Wrote ${out} (${products.length} products, ${categories.length} categories, ${collections.length} collections)`)
